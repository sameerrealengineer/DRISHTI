// Generates CSS variables for the web app from tokens.json (Dart output lands with the Flutter apps).
//   node packages/design-tokens/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const vars = (group, prefix) =>
  Object.entries(t[group]).map(([k, v]) => `  --${prefix}${k}: ${v};`).join("\n");
const css = `/* Generated by packages/design-tokens/build.mjs — do not edit. */
:root {
${vars("dark", "")}
${vars("levels", "lv-")}
${vars("citizen", "c-")}
  --font-display: "${t.fonts.display}", system-ui, sans-serif;
  --font-body: "${t.fonts.body}", "${t.fonts.odia}", system-ui, sans-serif;
  --font-mono: "${t.fonts.mono}", ui-monospace, monospace;
}
`;
writeFileSync(join(here, "../../apps/web/src/theme/tokens.css"), css);
console.log("wrote apps/web/src/theme/tokens.css");
